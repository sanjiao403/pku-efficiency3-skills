#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""render_svg -- scene -> layered, hand-editable SVG.

Design rules that matter for the rubric:
  * real <text> elements (never converted to paths), so every label stays
    editable in Illustrator / Inkscape / Figma / a text editor;
  * one <g id="layer-*"> per semantic layer, in reading order;
  * every drawn element carries the same id that result.json content_map uses,
    so an element on the canvas can be traced back to the source material;
  * fill + hatch pattern are two stacked rects, so the figure survives greyscale
    printing and colour-vision deficiency without a second artwork.
"""

from __future__ import annotations

import sys as _sys
_sys.dont_write_bytecode = True  # never leave __pycache__ behind



def _esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def _n(v):
    try:
        f = float(v)
    except Exception:
        return "0"
    if abs(f - round(f)) < 0.05:
        return str(int(round(f)))
    return ("%.1f" % f).rstrip("0").rstrip(".")


FONT_STACK = ("'DejaVu Sans','Noto Sans CJK SC','Source Han Sans SC',"
              "'Microsoft YaHei','PingFang SC',Helvetica,Arial,sans-serif")
MONO_STACK = "'DejaVu Sans Mono',Menlo,Consolas,monospace"

PATTERN_DEFS = {
    "hatch45": ('<pattern id="pat-hatch45" width="9" height="9" patternUnits="userSpaceOnUse" '
                'patternTransform="rotate(45)"><line x1="0" y1="0" x2="0" y2="9" '
                'stroke="#1A1A1E" stroke-width="1.1" stroke-opacity="0.26"/></pattern>'),
    "hatch135": ('<pattern id="pat-hatch135" width="9" height="9" patternUnits="userSpaceOnUse" '
                 'patternTransform="rotate(-45)"><line x1="0" y1="0" x2="0" y2="9" '
                 'stroke="#1A1A1E" stroke-width="1.1" stroke-opacity="0.26"/></pattern>'),
    "hatch90": ('<pattern id="pat-hatch90" width="6" height="6" patternUnits="userSpaceOnUse">'
                '<line x1="0" y1="0" x2="0" y2="6" stroke="#1A1A1E" stroke-width="1.1" '
                'stroke-opacity="0.26"/></pattern>'),
    "dots": ('<pattern id="pat-dots" width="9" height="9" patternUnits="userSpaceOnUse">'
             '<circle cx="3.5" cy="3.5" r="1.25" fill="#1A1A1E" fill-opacity="0.30"/></pattern>'),
    "cross": ('<pattern id="pat-cross" width="10" height="10" patternUnits="userSpaceOnUse">'
              '<path d="M0 0 L10 10 M10 0 L0 10" " stroke="#1A1A1E" stroke-width="1" '
              'stroke-opacity="0.24"/></pattern>'),
    "grid": ('<pattern id="pat-grid" width="10" height="10" patternUnits="userSpaceOnUse">'
             '<path d="M0 5 H10 M5 0 V10" stroke="#1A1A1E" stroke-width="0.9" '
             'stroke-opacity="0.22"/></pattern>'),
}


def _sanitize(pid, used):
    base = "".join(ch if (ch.isalnum() or ch in "-_.") else "-" for ch in str(pid or "el"))
    if not base or not (base[0].isalpha() or base[0] == "_"):
        base = "el-" + base
    cand = base
    n = 2
    while cand in used:
        cand = "%s-%d" % (base, n)
        n += 1
    used.add(cand)
    return cand


def scene_to_svg(scene, meta=None) -> dict:
    meta = meta or {}
    W = scene["canvas"]["width_px"]
    H = scene["canvas"]["height_px"]
    used = set()
    ids = {}
    out = []
    out.append('<?xml version="1.0" encoding="UTF-8"?>')
    out.append('<svg xmlns="http://www.w3.org/2000/svg" version="1.1" '
               'width="%s" height="%s" viewBox="0 0 %s %s" '
               'shape-rendering="geometricPrecision" text-rendering="geometricPrecision">'
               % (_n(W), _n(H), _n(W), _n(H)))
    title = _esc(meta.get("title") or "Graphical abstract")
    out.append("  <title>%s</title>" % title)
    desc = meta.get("description") or (
        "Editable graphical abstract generated by the graphical-abstract-svg skill. "
        "Text is real <text>; every element id matches result.json content_map.")
    out.append("  <desc>%s</desc>" % _esc(desc))
    out.append('  <metadata>%s</metadata>' % _esc(
        "case_id=%s; generator=graphical-abstract-svg/%s; layers=%s" % (
            meta.get("case_id", ""), meta.get("version", ""), ",".join(scene["layers"]))))
    out.append("  <defs>")
    for pat in scene["patterns"]:
        if pat in PATTERN_DEFS:
            out.append("    " + PATTERN_DEFS[pat])
    out.append("  </defs>")

    by_layer = {l: [] for l in scene["layers"]}
    for p in scene["prims"]:
        by_layer.setdefault(p["layer"], []).append(p)

    for layer in scene["layers"]:
        out.append('  <g id="layer-%s" data-layer="%s">' % (layer, layer))
        for p in by_layer.get(layer, []):
            pid = _sanitize(p.get("id") or "", used)
            if p.get("id"):
                ids[p["id"]] = pid
            elem_id = ' id="%s"' % pid
            t = p["t"]
            if t == "rect":
                base = ('<rect%s x="%s" y="%s" width="%s" height="%s" rx="%s" fill="%s" '
                        'stroke="%s" stroke-width="%s"%s%s/>' % (
                            elem_id, _n(p["x"]), _n(p["y"]), _n(max(0, p["w"])),
                            _n(max(0, p["h"])), _n(p["rx"]), _esc(p["fill"]),
                            _esc(p["stroke"]), _n(p["sw"]),
                            ' stroke-dasharray="%s"' % p["dash"] if p["dash"] else "",
                            ' opacity="%s"' % _n(p["opacity"]) if p.get("opacity") else ""))
                out.append("    " + base)
                pat = p.get("pattern") or ""
                if pat and pat in PATTERN_DEFS:
                    out.append('    <rect x="%s" y="%s" width="%s" height="%s" rx="%s" '
                               'fill="url(#pat-%s)" stroke="none"/>' % (
                                   _n(p["x"]), _n(p["y"]), _n(max(0, p["w"])),
                                   _n(max(0, p["h"])), _n(p["rx"]), pat))
            elif t == "line":
                out.append('    <line%s x1="%s" y1="%s" x2="%s" y2="%s" stroke="%s" '
                           'stroke-width="%s"%s stroke-linecap="round"/>' % (
                               elem_id, _n(p["x1"]), _n(p["y1"]), _n(p["x2"]), _n(p["y2"]),
                               _esc(p["stroke"]), _n(p["sw"]),
                               ' stroke-dasharray="%s"' % p["dash"] if p["dash"] else ""))
            elif t == "poly":
                pts = " ".join("%s,%s" % (_n(a), _n(b)) for a, b in p["pts"])
                out.append('    <polygon%s points="%s" fill="%s" stroke="%s" stroke-width="%s"/>'
                           % (elem_id, pts, _esc(p["fill"]), _esc(p["stroke"]), _n(p["sw"])))
            elif t == "circle":
                out.append('    <circle%s cx="%s" cy="%s" r="%s" fill="%s" stroke="%s" '
                           'stroke-width="%s"/>' % (elem_id, _n(p["cx"]), _n(p["cy"]),
                                                    _n(p["r"]), _esc(p["fill"]),
                                                    _esc(p["stroke"]), _n(p["sw"])))
            elif t == "text":
                attrs = []
                if p.get("bold"):
                    attrs.append('font-weight="700"')
                if p.get("italic"):
                    attrs.append('font-style="italic"')
                fam = MONO_STACK if p.get("family") == "mono" else FONT_STACK
                out.append('    <text%s x="%s" y="%s" font-family="%s" font-size="%s" '
                           'fill="%s" text-anchor="%s" %s>%s</text>' % (
                               elem_id, _n(p["x"]), _n(p["y"]), fam, _n(p["size"]),
                               _esc(p["fill"]), p["anchor"], " ".join(attrs),
                               _esc(p["s"])))
        out.append("  </g>")
    out.append("</svg>")
    svg = "\n".join(out) + "\n"
    return {"svg": svg, "ids": ids, "text_count": scene["text_count"],
            "bytes": len(svg.encode("utf-8"))}


